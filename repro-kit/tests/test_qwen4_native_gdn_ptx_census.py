"""Offline tests for the batched-GDN embedded-PTX census.

Synthetic ELF and PTX fixtures reproduce the NVVM text shape of both kernel
variants (lines modeled on real sm_121f output). Source-contract checks read
the tree the census is shipped in. Nothing is built, run or loaded.
"""

import importlib.machinery
import importlib.util
import os
from pathlib import Path
import re
import shutil
import struct
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
TREE = ROOT.parent


def module(path, name):
    loader = importlib.machinery.SourceFileLoader(name, str(path))
    spec = importlib.util.spec_from_loader(name, loader)
    value = importlib.util.module_from_spec(spec)
    sys.modules[name] = value
    loader.exec_module(value)
    return value


C = module(ROOT / "qwen4_native_gdn_ptx_census.py", "qwen4_native_gdn_ptx_census")
LOCAL = "_ZZ37gated_delta_rule_decode_f32_multi_seqE"
HEADER = (
    "//\n// Generated by NVIDIA NVVM Compiler\n//\n// Compiler Build ID: CL-36424714\n"
    "// Cuda compilation tools, release 13.0, V13.0.88\n// Based on NVVM 20.0.0\n//\n\n"
    ".version 9.0\n.target sm_121f\n.address_size 64\n\n"
    "\t// .globl\tgated_delta_rule_decode_f32_multi_seq\n"
)
CLAMP_BODY = (
    f"\tshfl.sync.down.b32\t%r371|%p25, %r370, 16, 31, %r369;\n"
    f"\tmov.u32 \t%r382, {LOCAL}9norm_sums;\n"
    f"\tsetp.leu.ftz.f32 \t%p34, %f33, 0f49742400;\n"
    f"\trsqrt.approx.ftz.f32 \t%f388, %f33;\n"
    f"\tmul.rn.ftz.f32 \t%f34, %f388, 0f447A0000;\n"
)


def ptx(clamped=True, smem=True, extra_clamp=None, closed=True):
    demoted = [f"// {LOCAL}6smem_k has been demoted", f"// {LOCAL}6smem_q has been demoted"] if smem else []
    if clamped:
        demoted.append(f"// {LOCAL}9norm_sums has been demoted")
    body = [
        ".visible .entry gated_delta_rule_decode_f32_multi_seq(",
        "\t.param .u64 .ptr .align 1 gated_delta_rule_decode_f32_multi_seq_param_0,",
        "\t.param .u32 gated_delta_rule_decode_f32_multi_seq_param_15",
        ")",
        "{",
        "\t.reg .pred \t%p<64>;",
        f"\t.shared .align 4 .b8 {LOCAL}6smem_k[512];" if smem else "",
        f"\t.shared .align 4 .b8 {LOCAL}6smem_q[512];" if smem else "",
        "\tld.global.nc.f32 \t%f1, [%rd1];",
        "\t{ // callseq 0, 0",
        "\t}",
        CLAMP_BODY if clamped else (extra_clamp or ""),
        "\trsqrt.approx.ftz.f32 \t%f448, %f447;",
        "\tst.global.f32 \t[%rd9], %f449;",
        "\tret;",
        "}" if closed else "",
        "",
    ]
    return (HEADER + "\n".join(demoted) + "\n\n" + "\n".join(body)).encode()


def other_module():
    return (HEADER.replace("gated_delta_rule_decode_f32_multi_seq", "w4a16_gemv")
            + ".visible .entry w4a16_gemv(\n\t.param .u64 p\n)\n{\n\tret;\n}\n").encode()


def elf(*modules):
    # include_str! data is contiguous in .rodata: no NUL between PTX strings.
    return b"\x7fELF\x02\x01\x01" + b"\x00" * 57 + b"".join(modules) + b"\x00" * 32


class CensusTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.base = Path(self.temp.name)

    def tearDown(self):
        self.temp.cleanup()

    def write(self, raw, name="spark"):
        path = self.base / name
        path.write_bytes(raw)
        return path

    def run_census(self, raw, kind="elf", source=TREE, chunk=C.CHUNK):
        return C.bind_source(C.census(self.write(raw), kind, chunk), source)

    def test_single_flash_next_twin_is_fix_present(self):
        result = self.run_census(elf(other_module(), ptx(clamped=False), other_module()))
        self.assertEqual(result["verdict"], C.FIX_PRESENT, result["reasons"])
        self.assertTrue(result["source_marker"]["present"])
        self.assertEqual(result["entries"][0]["ptx_target"], "sm_121f")

    def test_attribution_requires_the_source_root(self):
        result = self.run_census(elf(ptx(clamped=False)), source=None)
        self.assertEqual(result["verdict"], C.INCOMPLETE)

    def test_clamped_only_is_fix_absent(self):
        result = self.run_census(elf(ptx(clamped=True)))
        self.assertEqual(result["verdict"], C.FIX_ABSENT)

    def test_multi_target_binary_attributes_the_clamp_free_twin(self):
        result = self.run_census(elf(ptx(clamped=True), other_module(), ptx(clamped=False)))
        self.assertEqual(result["verdict"], C.FIX_PRESENT)
        self.assertEqual(result["counts"], {"clamp_absent": 1, "clamp_present": 1, "ambiguous": 0})

    def test_two_clamp_free_twins_cannot_be_attributed(self):
        result = self.run_census(elf(ptx(clamped=False), ptx(clamped=False)))
        self.assertEqual(result["verdict"], C.INCOMPLETE)

    def test_no_entry_is_incomplete(self):
        self.assertEqual(self.run_census(elf(other_module()))["verdict"], C.INCOMPLETE)

    def test_partial_clamp_signature_is_ambiguous(self):
        partial = "\tshfl.sync.down.b32\t%r1|%p1, %r2, 16, 31, %r3;\n"
        result = self.run_census(elf(ptx(clamped=False, extra_clamp=partial)))
        self.assertEqual(result["entries"][0]["classification"], "AMBIGUOUS")
        self.assertEqual(result["verdict"], C.INCOMPLETE)

    def test_missing_structure_is_ambiguous(self):
        result = self.run_census(elf(ptx(clamped=False, smem=False)))
        self.assertEqual(result["entries"][0]["classification"], "AMBIGUOUS")
        self.assertEqual(result["verdict"], C.INCOMPLETE)

    def test_non_elf_input_is_refused_unless_ptx(self):
        raw = ptx(clamped=False)
        self.assertEqual(self.run_census(raw)["verdict"], C.INCOMPLETE)
        self.assertEqual(self.run_census(raw, kind="ptx")["verdict"], C.FIX_PRESENT)

    def test_chunk_boundaries_do_not_hide_an_entry(self):
        raw = elf(ptx(clamped=True), other_module(), ptx(clamped=False))
        wide = C.census(self.write(raw, "a"), "elf")
        for chunk in (7, 31, 64, 1000):
            narrow = C.census(self.write(raw, f"b{chunk}"), "elf", chunk)
            self.assertEqual([e["offset"] for e in narrow["entries"]], [e["offset"] for e in wide["entries"]])
            self.assertEqual(narrow["file_sha256"], wide["file_sha256"])

    def test_unclosed_body_is_incomplete(self):
        self.assertEqual(self.run_census(elf(ptx(clamped=False, closed=False)))["verdict"], C.INCOMPLETE)

    def test_nul_inside_module_is_incomplete(self):
        raw = ptx(clamped=False).replace(b".address_size 64", b".address_size 64\x00")
        self.assertEqual(self.run_census(elf(raw))["verdict"], C.INCOMPLETE)

    def test_symlinked_binary_is_refused(self):
        target = self.write(elf(ptx(clamped=False)))
        link = self.base / "link"
        os.symlink(target, link)
        self.assertEqual(C.census(link)["verdict"], C.INCOMPLETE)

    def copy_tree(self):
        root = self.base / "tree"
        for relative in (C.SOURCE_OVERRIDE, C.SOURCE_COMMON, C.SOURCE_LOADER):
            (root / relative).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(TREE / relative, root / relative)
        return root

    def test_source_contract_holds_in_this_tree(self):
        marker = C.source_marker(TREE)
        self.assertTrue(marker["present"], marker)

    def test_removed_define_downgrades_fix_present(self):
        root = self.copy_tree()
        override = root / C.SOURCE_OVERRIDE
        override.write_text(override.read_text().replace(C.OVERRIDE_DEFINE, ""))
        result = self.run_census(elf(ptx(clamped=False)), source=root)
        self.assertEqual(result["verdict"], C.INCOMPLETE)
        self.assertIn("override_defines_before_include", result["source_marker"]["reasons"])

    def test_second_definer_breaks_attribution(self):
        root = self.copy_tree()
        rogue = root / "kernels/gb10/other-model/nvfp4/gated_delta_rule_f32_multi_seq.cu"
        rogue.parent.mkdir(parents=True)
        rogue.write_text(C.OVERRIDE_DEFINE + "\n")
        marker = C.source_marker(root)
        self.assertFalse(marker["checks"]["define_unique_to_flash_next"])

    def test_ptx_markers_are_the_compiled_form_of_the_source(self):
        common = (TREE / C.SOURCE_COMMON).read_text()
        self.assertIn("#define SSM_STATE_MAX_NORM 1000.0f", common)
        self.assertIn("head_norm_sq > SSM_STATE_MAX_NORM * SSM_STATE_MAX_NORM", common)
        for name in ("__shared__ float norm_sums[4];", "__shfl_down_sync", "__shared__ float smem_k[128];",
                     "__shared__ float smem_q[128];", "rsqrtf((float)k_dim)"):
            self.assertIn(name, common)
        self.assertRegex(
            common,
            rf'extern "C" __global__ (?:__launch_bounds__\([^)]*\)\s+)?void {re.escape(C.ENTRY)}\(',
        )
        self.assertEqual("0f" + struct.pack(">f", 1000.0).hex(), "0f447a0000")
        self.assertEqual("0f" + struct.pack(">f", 1000.0 * 1000.0).hex(), "0f49742400")


if __name__ == "__main__":
    unittest.main()
