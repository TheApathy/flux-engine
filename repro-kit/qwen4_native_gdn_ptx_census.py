"""Shipped-binary census: is the Flash-Next C1-matching batched GDN kernel embedded?

The native C2-C32 lane advances recurrent state with
`gated_delta_rule_decode_f32_multi_seq`, which is loaded from PTX module
`gated_delta_rule_f32_multi_seq` (crates/spark-model/src/layers/qwen3_ssm/init.rs).
The shared source (kernels/gb10/common/gated_delta_rule_f32_multi_seq.cu)
rescales every value head's state to Frobenius norm 1000 after each step
unless `ATLAS_GDN_MULTI_SEQ_NO_STATE_NORM` is defined. The Flash-Next C1
kernel has no such clamp, so the Flash-Next override
(kernels/gb10/qwen3.8-flash-next/nvfp4/gated_delta_rule_f32_multi_seq.cu)
defines the macro and includes the common file. atlas-kernels embeds PTX text
with include_str!, and a warm build does not notice a new .cu, so source
alone does not prove what the ELF carries.

The clamp compiles to a warp-shuffle reduction over a function-scope shared
array `norm_sums`, plus the float constants 1e6 (0f49742400, the squared
bound) and 1000 (0f447A0000). Both variants keep `smem_k`/`smem_q` and the
rsqrt of k_dim, which the census uses as structural controls.

The ELF does not say which kernel target owns which PTX string, and a
multi-target binary legitimately embeds a clamped twin for other models. The
attribution therefore rests on a source invariant that `--source-root`
checks: the Flash-Next override is the only file that defines
ATLAS_GDN_MULTI_SEQ_NO_STATE_NORM, so a clamp-free twin can only have been
compiled for the Flash-Next target.

Verdicts:
* FIX_PRESENT: exactly one clamp-free entry (any number of clamped twins of
  other targets are reported, not judged).
* FIX_ABSENT: at least one entry and none is clamp-free, so a Flash-Next
  target in this binary would run the clamped twin.
* DIAGNOSTIC_INCOMPLETE: anything else (no entry, an entry matching neither
  signature, several clamp-free entries, unreadable or non-ELF input).
Read only; never builds, runs or loads the binary.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys

SCHEMA = "flux-qwen4-native-gdn-ptx-census/1"
ENTRY = "gated_delta_rule_decode_f32_multi_seq"
MODULE = "gated_delta_rule_f32_multi_seq"
NEEDLE = (".entry " + ENTRY + "(").encode()
PTX_HEADER = b"// Generated by NVIDIA NVVM Compiler"
FIX_PRESENT, FIX_ABSENT, INCOMPLETE = "FIX_PRESENT", "FIX_ABSENT", "DIAGNOSTIC_INCOMPLETE"
CHUNK = 8 << 20
MODULE_LOOKBACK = 1 << 20
BODY_LIMIT = 1 << 20
# The clamp's PTX signature; each must be absent for CLAMP_ABSENT.
CLAMP_MARKERS = {
    "warp_shuffle": re.compile(rb"shfl\.sync\.down"),
    "norm_sums_shared": re.compile(rb"norm_sums"),
    "max_norm_squared_1e6": re.compile(rb"0f49742400", re.IGNORECASE),
    "max_norm_1000": re.compile(rb"0f447a0000", re.IGNORECASE),
}
# Present in both variants: proves the parsed region is this kernel.
STRUCTURE_MARKERS = {
    "smem_k_shared": re.compile(rb"smem_k"),
    "smem_q_shared": re.compile(rb"smem_q"),
    "rsqrt": re.compile(rb"rsqrt\.approx"),
    "ret": re.compile(rb"\bret;"),
}
# Source contract of the fix (paths relative to the tree root).
SOURCE_OVERRIDE = Path("kernels/gb10/qwen3.8-flash-next/nvfp4/gated_delta_rule_f32_multi_seq.cu")
SOURCE_COMMON = Path("kernels/gb10/common/gated_delta_rule_f32_multi_seq.cu")
SOURCE_LOADER = Path("crates/spark-model/src/layers/qwen3_ssm/init.rs")
OVERRIDE_DEFINE = "#define ATLAS_GDN_MULTI_SEQ_NO_STATE_NORM 1"
OVERRIDE_INCLUDE = '#include "../../common/gated_delta_rule_f32_multi_seq.cu"'
COMMON_GUARD = "#if !defined(SSM_STATE_NORM_ENABLED) && !defined(ATLAS_GDN_MULTI_SEQ_NO_STATE_NORM)"


class CensusError(ValueError):
    pass


def require(condition, message):
    if not condition:
        raise CensusError(message)


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode()


def open_regular(path):
    path = Path(path)
    require(not path.is_symlink(), f"{path.name}: symlinks are not followed")
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    info = os.fstat(descriptor)
    if not stat.S_ISREG(info.st_mode):
        os.close(descriptor)
        raise CensusError(f"{path.name}: not a regular file")
    return descriptor, info.st_size


def read_at(descriptor, offset, length):
    return os.pread(descriptor, length, offset)


def scan(descriptor, size, chunk=CHUNK):
    """Stream the file once: SHA-256 plus every NEEDLE offset (chunk-boundary safe)."""
    digest = hashlib.sha256()
    offsets, carry, base = [], b"", 0
    overlap = len(NEEDLE) - 1
    while base < size:
        data = read_at(descriptor, base, min(chunk, size - base))
        require(data, "file shrank while scanning")
        digest.update(data)
        window = carry + data
        start = base - len(carry)
        position = window.find(NEEDLE)
        while position >= 0:
            offsets.append(start + position)
            position = window.find(NEEDLE, position + 1)
        carry = window[-overlap:] if overlap else b""
        base += len(data)
    return digest.hexdigest(), sorted(set(offsets))


def entry_body(descriptor, size, offset):
    """Bytes from NEEDLE to the brace closing the entry body."""
    raw = read_at(descriptor, offset, min(BODY_LIMIT, size - offset))
    params_end = raw.find(b")")
    open_brace = raw.find(b"{", params_end)
    require(params_end > 0 and open_brace > params_end, "entry has no parameter list or body")
    depth = 0
    for index in range(open_brace, len(raw)):
        byte = raw[index]
        if byte == 0x7B:
            depth += 1
        elif byte == 0x7D:
            depth -= 1
            if depth == 0:
                return raw[: index + 1]
        elif byte == 0:
            break
    raise CensusError("entry body is not closed within the scan limit")


def module_prefix(descriptor, offset):
    """Module text before the entry: back to the nearest NVVM header, bounded."""
    lo = max(0, offset - MODULE_LOOKBACK)
    raw = read_at(descriptor, lo, offset - lo)
    header = raw.rfind(PTX_HEADER)
    require(header >= 0, "no NVVM PTX header precedes the entry")
    prefix = raw[header:]
    require(b"\x00" not in prefix, "entry is not inside one contiguous PTX string")
    require(prefix.count(b".entry ") == 0, "module holds another entry before this kernel")
    return prefix


def classify(prefix, body):
    region = prefix + body
    clamp = {name: bool(pattern.search(region)) for name, pattern in CLAMP_MARKERS.items()}
    structure = {name: bool(pattern.search(region)) for name, pattern in STRUCTURE_MARKERS.items()}
    if not all(structure.values()):
        kind = "AMBIGUOUS"
    elif not any(clamp.values()):
        kind = "CLAMP_ABSENT"
    elif clamp["warp_shuffle"] and clamp["norm_sums_shared"]:
        kind = "CLAMP_PRESENT"
    else:
        kind = "AMBIGUOUS"
    target = re.search(rb"\.target\s+(sm_[0-9a-z]+)", prefix)
    return {
        "classification": kind,
        "clamp_markers": clamp,
        "structure_markers": structure,
        "ptx_target": target.group(1).decode() if target else None,
        "entry_body_sha256": hashlib.sha256(body).hexdigest(),
        "entry_body_bytes": len(body),
    }


def census(path, kind="elf", chunk=CHUNK):
    """Census one ELF (or loose .ptx). Never raises; failures become INCOMPLETE."""
    result = {"schema": SCHEMA, "entry": ENTRY, "module": MODULE, "kind": kind,
              "file_sha256": None, "entries": [], "verdict": INCOMPLETE, "reasons": []}
    try:
        descriptor, size = open_regular(path)
    except (OSError, CensusError) as error:
        result["reasons"].append(f"cannot open: {error}")
        return result
    try:
        magic = read_at(descriptor, 0, 4)
        if kind == "elf":
            require(magic == b"\x7fELF", "not an ELF file")
        result["file_sha256"], offsets = scan(descriptor, size, chunk)
        for offset in offsets:
            prefix = module_prefix(descriptor, offset)
            body = entry_body(descriptor, size, offset)
            result["entries"].append({"offset": offset, **classify(prefix, body)})
    except (OSError, CensusError) as error:
        result["reasons"].append(str(error))
        return result
    finally:
        os.close(descriptor)
    return decide(result)


def decide(result):
    kinds = [entry["classification"] for entry in result["entries"]]
    absent, present = kinds.count("CLAMP_ABSENT"), kinds.count("CLAMP_PRESENT")
    result["counts"] = {"clamp_absent": absent, "clamp_present": present,
                        "ambiguous": len(kinds) - absent - present}
    if not kinds:
        result["reasons"].append(f"no embedded {ENTRY} entry")
    elif absent + present != len(kinds):
        result["reasons"].append("an embedded entry matches neither variant's PTX signature")
    elif absent == 1:
        result["verdict"] = FIX_PRESENT
        result["reasons"].append(
            "one clamp-free batched GDN twin is embedded (matches the Flash-Next C1 recurrence); "
            f"{present} clamped twin(s) of other targets are not judged"
        )
    elif absent == 0:
        result["verdict"] = FIX_ABSENT
        result["reasons"].append(
            "every embedded batched GDN twin clamps state norm to 1000; Flash-Next C1 does not"
        )
    else:
        result["reasons"].append(f"{absent} clamp-free twins cannot be attributed to one target")
    return result


def source_marker(root):
    """Check the fix's source contract in a tree; returns a dict, never raises."""
    root = Path(root)
    checks = {}
    try:
        override = (root / SOURCE_OVERRIDE).read_text()
        common = (root / SOURCE_COMMON).read_text()
        loader = (root / SOURCE_LOADER).read_text()
    except OSError as error:
        return {"present": False, "reasons": [str(error)], "checks": checks}
    define_at, include_at = override.find(OVERRIDE_DEFINE), override.find(OVERRIDE_INCLUDE)
    checks["override_defines_before_include"] = 0 <= define_at < include_at
    checks["common_guard"] = COMMON_GUARD in common
    checks["loader_module_and_entry"] = bool(
        re.search(r'"' + MODULE + r'",\s*"' + ENTRY + r'"', loader)
    )
    definers = sorted(
        str(path.relative_to(root))
        for path in (root / "kernels").rglob("*")
        if path.suffix in (".cu", ".cuh") and path.is_file() and not path.is_symlink()
        and re.search(r"^\s*#\s*define\s+ATLAS_GDN_MULTI_SEQ_NO_STATE_NORM\b", path.read_text(errors="replace"), re.M)
    )
    checks["define_unique_to_flash_next"] = definers == [str(SOURCE_OVERRIDE)]
    present = all(checks.values())
    return {"present": present, "checks": checks,
            "reasons": [] if present else [name for name, ok in checks.items() if not ok]}


def bind_source(result, root):
    """Attribution needs the source invariant; without it FIX_PRESENT is not proven."""
    if root is None:
        if result["verdict"] == FIX_PRESENT:
            result["verdict"] = INCOMPLETE
            result["reasons"].append("attribution unproven: pass --source-root of the built tree")
        return result
    result["source_marker"] = source_marker(root)
    if not result["source_marker"]["present"] and result["verdict"] != INCOMPLETE:
        result["verdict"] = INCOMPLETE
        result["reasons"].append("the source tree does not carry the fix contract: "
                                 + ", ".join(result["source_marker"]["reasons"]))
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("--binary", required=True)
    parser.add_argument("--kind", choices=("elf", "ptx"), default="elf")
    parser.add_argument("--source-root")
    args = parser.parse_args(argv)
    result = bind_source(census(args.binary, args.kind), args.source_root)
    sys.stdout.write(canonical(result).decode() + "\n")
    return {FIX_PRESENT: 0, FIX_ABSENT: 1}.get(result["verdict"], 3)


if __name__ == "__main__":
    raise SystemExit(main())
