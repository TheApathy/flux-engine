"""Export the MODEL.toml [[dflash.profile]] rows the launcher reads.

The engine compiles kernels/<hw>/*/MODEL.toml [[dflash.profile]] into its
drafter admission table (crates/atlas-kernels/build_profile.rs). The image's
launcher has no kernels/ tree, so it reads this export of the same rows:
repro-kit/recipes/drafter-profiles.json. tests/test_drafter_profiles.py fails
when the export and MODEL.toml disagree.

    python3 repro-kit/scripts/drafter_profiles.py          # rewrite the export
    python3 repro-kit/scripts/drafter_profiles.py --check  # exit 1 on drift
"""

import argparse
import json
import sys
import tomllib
from pathlib import Path

KIT = Path(__file__).resolve().parents[1]
KERNELS = KIT.parent / "kernels" / "gb10"
EXPORT = KIT / "recipes" / "drafter-profiles.json"

# Launcher-facing fields, with the Rust defaults for omitted keys.
FIELDS = {
    "name": None,
    "kind": None,
    "admission": None,
    "qualified": False,
    "launcher_default": False,
    "capture_mode": "residual_slice",
}


def collect(kernels: Path = KERNELS) -> dict:
    rows = []
    for model_toml in sorted(kernels.glob("*/MODEL.toml")):
        with model_toml.open("rb") as handle:
            profiles = tomllib.load(handle).get("dflash", {}).get("profile", [])
        for profile in profiles:
            row = {"target_model": model_toml.parent.name}
            for key, default in FIELDS.items():
                if default is None and key not in profile:
                    raise ValueError(f"{model_toml}: [[dflash.profile]] row lacks `{key}`")
                row[key] = profile.get(key, default)
            rows.append(row)
    return {
        "_comment": "Generated by repro-kit/scripts/drafter_profiles.py from "
        "kernels/gb10/*/MODEL.toml [[dflash.profile]]; do not edit.",
        "profiles": rows,
    }


def render(data: dict) -> str:
    return json.dumps(data, indent=2, sort_keys=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the export is stale")
    args = parser.parse_args()
    text = render(collect())
    if args.check:
        if not EXPORT.is_file() or EXPORT.read_text(encoding="utf-8") != text:
            print(f"{EXPORT} is stale; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    EXPORT.write_text(text, encoding="utf-8")
    print(f"wrote {EXPORT} ({len(json.loads(text)['profiles'])} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
