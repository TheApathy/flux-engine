/// Build-time AOT CUBIN metadata embedded into `target_ptx.rs`.
#[cfg(not(test))]
pub(super) struct AotCubinArtifact {
    pub ptx_len: usize,
    pub ptx_sha256: [u8; 32],
}

/// Metadata for a single compiled kernel module in a target.
#[cfg(not(test))]
pub(super) struct ModuleArtifact {
    pub stem: String,
    pub module_name: String,
    pub aot_cubin: Option<AotCubinArtifact>,
}

pub(super) fn obfuscate_ptx_bytes(src: &[u8]) -> Vec<u8> {
    let mut s: u64 = 0x9e37_79b9_7f4a_7c15 ^ (src.len() as u64).wrapping_mul(0xbf58_476d_1ce4_e5b9);
    src.iter()
        .map(|&b| {
            s = s.wrapping_add(0x9e37_79b9_7f4a_7c15);
            let mut z = s;
            z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
            z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
            z ^= z >> 31;
            b ^ (z as u8)
        })
        .collect()
}

/// Decide whether AOT CUBIN compilation & embedding should run for a target.
///
/// - Never embeds for non-text backends (Metal/HSACO/SPIR-V) or virtual arches
///   that do not start with `"sm_"`.
/// - Respects explicit env overrides (`"1"` / `"true"` forces ON; `"0"` /
///   `"false"` forces OFF).
/// - Defaults ON for single-target specialized builds (`target_count == 1`) and
///   OFF for multi-target universal builds to avoid multi-target binary bloat.
pub(super) fn should_embed_cubin(
    output_is_text: bool,
    target_count: usize,
    arch: &str,
    env_override: Option<&str>,
) -> bool {
    if !output_is_text || !arch.starts_with("sm_") {
        return false;
    }
    match env_override.map(str::trim) {
        Some("1" | "true" | "TRUE" | "yes" | "YES") => true,
        Some("0" | "false" | "FALSE" | "no" | "NO") => false,
        _ => target_count == 1,
    }
}

/// Extract `ptxas`-specific options forwarded via `-Xptxas` or `--ptxas-options`
/// from an `nvcc` flag list.
///
/// Non-`ptxas` flags (e.g. `--atlas-ieee-math`, `--fmad=false`, `-D...`, `-I...`,
/// `-std=...`, `-Xcudafe ...`) are omitted because their effects are already
/// baked into the `.ptx` generated by `nvcc --ptx` — in particular,
/// `nvcc --ptx --fmad=false` already emits explicit `.rn` instructions that the
/// PTX ISA forbids contracting, and invoking `ptxas -O3` matches runtime
/// `cuModuleLoadData` JIT behavior.
pub(super) fn extract_ptxas_flags(extra_flags: &[String]) -> Vec<String> {
    fn push_split(raw: &str, out: &mut Vec<String>) {
        for part in raw.split(|c: char| c == ',' || c.is_ascii_whitespace()) {
            let trimmed = part.trim();
            if !trimmed.is_empty() {
                out.push(trimmed.to_owned());
            }
        }
    }

    let mut out = Vec::new();
    let mut i = 0;
    while i < extra_flags.len() {
        let flag = extra_flags[i].as_str();
        match flag {
            "-Xptxas" | "--ptxas-options" => {
                if let Some(val) = extra_flags.get(i + 1) {
                    push_split(val, &mut out);
                    i += 2;
                } else {
                    i += 1;
                }
            }
            "-Xcompiler"
            | "--compiler-options"
            | "-Xcudafe"
            | "--cudafe-options"
            | "-Xlinker"
            | "--linker-options"
            | "-Xnvlink"
            | "--nvlink-options"
            | "-Xpreprocessor"
            | "--preprocessor-options" => {
                // Skip both the forwarder and its operand so another tool's
                // operand can never be misinterpreted as a ptxas option.
                i += 2;
            }
            _ => {
                if let Some(val) = flag
                    .strip_prefix("-Xptxas=")
                    .or_else(|| flag.strip_prefix("--ptxas-options="))
                {
                    push_split(val, &mut out);
                }
                i += 1;
            }
        }
    }
    out
}

/// Parse the `.target sm_...` architecture directive from a PTX header.
///
/// Returns `Some("sm_...")` when the header declares a concrete SM target (e.g.
/// `sm_121a` or `sm_121f`), ignoring trailing comma-separated target options such
/// as `texmode_independent`. Returns `None` if absent or non-SM.
pub(super) fn parse_ptx_target_arch(ptx_bytes: &[u8]) -> Option<String> {
    let prefix_len = ptx_bytes.len().min(8192);
    let head = std::str::from_utf8(&ptx_bytes[..prefix_len])
        .unwrap_or_else(|e| std::str::from_utf8(&ptx_bytes[..e.valid_up_to()]).unwrap_or(""));
    for line in head.lines() {
        let trimmed = line.trim();
        let Some(rest) = trimmed.strip_prefix(".target") else {
            continue;
        };
        if !rest.starts_with(char::is_whitespace) {
            continue;
        }
        let first_token = rest
            .trim_start()
            .split(|c: char| c == ',' || c.is_whitespace() || c == ';')
            .next()?;
        if first_token.starts_with("sm_") {
            return Some(first_token.to_owned());
        }
    }
    None
}

/// Generate the target_ptx.rs source with per-target kernel constants and
/// lookup functions.
///
/// `output_is_text` controls whether emitted constants are textual PTX
/// (`&'static str` via `include_str!`) or binary metallib/HSACO/SPIR-V
/// (`&'static [u8]` via `include_bytes!`). The two cases also pick
/// different output filenames (`.ptx` vs whatever `output_ext` says) and
/// different generated-API names (`ptx_modules` vs `metallib_modules`).
#[cfg(not(test))]
pub(super) fn generate_target_ptx_rs(
    targets: &[Target],
    all_modules: &[Vec<ModuleArtifact>],
    output_ext: &str,
    output_is_text: bool,
) -> String {
    let mut g = String::new();
    g.push_str("// Auto-generated by build.rs — do not edit.\n");
    g.push_str("// KernelTarget and TargetPtxSet are imported by the parent lib.rs.\n\n");

    // Naming scheme switches between text PTX and binary metallib/etc:
    //   text   → `pub const FOO_PTX: &str = include_str!(...)`,
    //            `pub fn ptx_modules() -> Vec<(&str, &str)>`
    //   binary → `pub const FOO_METALLIB: &[u8] = include_bytes!(...)`,
    //            `pub fn metallib_modules() -> Vec<(&str, &[u8])>`
    // `const_ty` drops the `'static` (consts default to `'static` —
    // clippy::redundant_static_lifetimes); `modules_ty` keeps it (no
    // elision possible for function return signature).
    let (const_suffix, const_ty, include_macro, fn_root, modules_ty) = if output_is_text {
        (
            "PTX",
            "&str",
            "include_str!",
            "ptx_modules",
            "Vec<(&'static str, &'static str)>",
        )
    } else {
        (
            "METALLIB",
            "&[u8]",
            "include_bytes!",
            "metallib_modules",
            "Vec<(&'static str, &'static [u8])>",
        )
    };

    let single_target = targets.len() == 1;
    let obfuscate = output_is_text
        && matches!(
            env::var("ATLAS_OBFUSCATE_PTX").as_deref(),
            Ok("1") | Ok("true")
        );
    let has_any_cubin = output_is_text
        && all_modules
            .iter()
            .any(|mods| mods.iter().any(|m| m.aot_cubin.is_some()));

    if obfuscate {
        g.push_str(
            "fn decode_obf_ptx(src: &'static [u8]) -> &'static str {\n\
             \x20   let mut s: u64 = 0x9e37_79b9_7f4a_7c15 ^ (src.len() as u64).wrapping_mul(0xbf58_476d_1ce4_e5b9);\n\
             \x20   let bytes: Vec<u8> = src.iter().map(|&b| {\n\
             \x20       s = s.wrapping_add(0x9e37_79b9_7f4a_7c15);\n\
             \x20       let mut z = s;\n\
             \x20       z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);\n\
             \x20       z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);\n\
             \x20       z ^= z >> 31;\n\
             \x20       b ^ (z as u8)\n\
             \x20   }).collect();\n\
             \x20   Box::leak(String::from_utf8(bytes).expect(\"valid obfuscated PTX\").into_boxed_str())\n\
             }\n\n",
        );
    }

    let mut cubin_table_entries = String::new();

    for (idx, (target, modules)) in targets.iter().zip(all_modules.iter()).enumerate() {
        let prefix = if single_target {
            String::new()
        } else {
            format!("T{idx}_")
        };

        // Kernel-blob constants
        for module in modules {
            let stem = &module.stem;
            let module_name = &module.module_name;
            let const_name = format!("{}{}_{}", prefix, module_name.to_uppercase(), const_suffix);
            if obfuscate {
                g.push_str(&format!(
                    "const {const_name}_OBF: &[u8] = \
                     include_bytes!(concat!(env!(\"ATLAS_PTX_DIR\"), \"/t{idx}__{stem}.{output_ext}.obf\"));\n"
                ));
            } else {
                g.push_str(&format!(
                    "pub const {const_name}: {const_ty} = \
                     {include_macro}(concat!(env!(\"ATLAS_PTX_DIR\"), \"/t{idx}__{stem}.{output_ext}\"));\n"
                ));
            }
            if output_is_text && let Some(ref cubin) = module.aot_cubin {
                let cubin_const = if obfuscate {
                    format!("{}{}_CUBIN_OBF", prefix, module_name.to_uppercase())
                } else {
                    format!("{}{}_CUBIN", prefix, module_name.to_uppercase())
                };
                let cubin_ext = if obfuscate { "cubin.obf" } else { "cubin" };
                g.push_str(&format!(
                    "const {cubin_const}: &[u8] = \
                     include_bytes!(concat!(env!(\"ATLAS_PTX_DIR\"), \"/t{idx}__{stem}.{cubin_ext}\"));\n"
                ));
                let sha_csv = cubin
                    .ptx_sha256
                    .iter()
                    .map(u8::to_string)
                    .collect::<Vec<_>>()
                    .join(", ");
                cubin_table_entries.push_str(&format!(
                    "    EmbeddedAotCubin {{\n\
                     \x20       module_name: \"{module_name}\",\n\
                     \x20       ptx_len: {},\n\
                     \x20       ptx_sha256: [{sha_csv}],\n\
                     \x20       bytes: {cubin_const},\n\
                     \x20   }},\n",
                    cubin.ptx_len
                ));
            }
        }
        g.push('\n');

        // Per-target lookup function
        let fn_name = if single_target {
            fn_root.to_string()
        } else {
            format!("{fn_root}_t{idx}")
        };
        let register_call = if output_is_text {
            "    register_embedded_aot_cubins();\n"
        } else {
            ""
        };
        g.push_str(&format!(
            "/// Kernel modules for target: ({}, {}, {}).\n",
            target.hw, target.model, target.quant
        ));
        if obfuscate {
            g.push_str(&format!(
                "pub fn {fn_name}() -> {modules_ty} {{\n\
                 {register_call}\
                 \x20   static DECODED: std::sync::OnceLock<{modules_ty}> = std::sync::OnceLock::new();\n\
                 \x20   DECODED.get_or_init(|| vec![\n"
            ));
            for module in modules {
                let module_name = &module.module_name;
                let const_name =
                    format!("{}{}_{}", prefix, module_name.to_uppercase(), const_suffix);
                g.push_str(&format!(
                    "        (\"{module_name}\", decode_obf_ptx({const_name}_OBF)),\n"
                ));
            }
            g.push_str("    ]).clone()\n}\n\n");
        } else {
            g.push_str(&format!(
                "pub fn {fn_name}() -> {modules_ty} {{\n\
                 {register_call}\
                 \x20   vec![\n"
            ));
            for module in modules {
                let module_name = &module.module_name;
                let const_name =
                    format!("{}{}_{}", prefix, module_name.to_uppercase(), const_suffix);
                g.push_str(&format!("        (\"{module_name}\", {const_name}),\n"));
            }
            g.push_str("    ]\n}\n\n");
        }
    }

    if has_any_cubin {
        let encoding_expr = if obfuscate {
            "atlas_core::target::AotCubinEncoding::Obfuscated"
        } else {
            "atlas_core::target::AotCubinEncoding::Raw"
        };
        g.push_str(&format!(
            "struct EmbeddedAotCubin {{\n\
             \x20   module_name: &'static str,\n\
             \x20   ptx_len: usize,\n\
             \x20   ptx_sha256: [u8; 32],\n\
             \x20   bytes: &'static [u8],\n\
             }}\n\n\
             const AOT_CUBIN_ENTRIES: &[EmbeddedAotCubin] = &[\n\
             {cubin_table_entries}\
             ];\n\n\
             pub(crate) fn register_embedded_aot_cubins() {{\n\
             \x20   static REGISTERED: std::sync::OnceLock<()> = std::sync::OnceLock::new();\n\
             \x20   REGISTERED.get_or_init(|| {{\n\
             \x20       for entry in AOT_CUBIN_ENTRIES {{\n\
             \x20           atlas_core::target::register_aot_cubin(\n\
             \x20               entry.module_name,\n\
             \x20               entry.ptx_len,\n\
             \x20               entry.ptx_sha256,\n\
             \x20               entry.bytes,\n\
             \x20               {encoding_expr},\n\
             \x20           );\n\
             \x20       }}\n\
             \x20   }});\n\
             }}\n\n"
        ));
    } else {
        g.push_str("pub(crate) fn register_embedded_aot_cubins() {}\n\n");
    }

    // For metal targets, emit empty stubs of the cuda-side API so the
    // existing surface (`ptx_modules`, `all_ptx_sets`) still type-checks.
    // Real Metal consumers read from `metallib_modules()` (above).
    if !output_is_text {
        g.push_str(
            "/// Empty PTX stub — this build targets a non-CUDA backend.\n\
             /// Use `metallib_modules()` (or the equivalent backend API).\n\
             pub fn ptx_modules() -> Vec<(&'static str, &'static str)> {\n\
             \x20   register_embedded_aot_cubins();\n\
             \x20   Vec::new()\n\
             }\n\
             \n\
             /// Empty PTX-set stub for non-CUDA targets.\n\
             pub fn all_ptx_sets() -> Vec<TargetPtxSet> {\n\
             \x20   register_embedded_aot_cubins();\n\
             \x20   Vec::new()\n\
             }\n\n",
        );
        return g;
    }

    // For multi-target builds, add backward-compat ptx_modules() alias
    if !single_target {
        g.push_str(
            "/// PTX modules for the default (first) target.\n\
             ///\n\
             /// Backward-compatible alias. Prefer `all_ptx_sets()` for multi-target builds.\n\
             pub fn ptx_modules() -> Vec<(&'static str, &'static str)> {\n\
             \x20   ptx_modules_t0()\n\
             }\n\n",
        );
    }

    // all_ptx_sets() function — always generated for cuda targets
    g.push_str(
        "/// All compiled kernel targets and their PTX module sets.\n\
         pub fn all_ptx_sets() -> Vec<TargetPtxSet> {\n\
         \x20   register_embedded_aot_cubins();\n\
         \x20   vec![\n",
    );
    for (idx, target) in targets.iter().enumerate() {
        // Strip trailing 'f' from arch for KernelTarget (sm_121f → sm_121)
        let arch_clean = target.arch.trim_end_matches('f');
        let fn_name = if single_target {
            "ptx_modules".to_string()
        } else {
            format!("ptx_modules_t{idx}")
        };
        let fmt_cat = |c: &SamplingCat| -> String {
            format!(
                "SamplingCategory {{ temperature: {:.2}, top_p: {:.2}, top_k: {}, presence_penalty: {:.2}, frequency_penalty: {:.2}, repetition_penalty: {:.2}, dry_multiplier: {:.2}, dry_base: {:.2}, dry_allowed_length: {}, lz_penalty: {:.2}, min_p: {}, top_n_sigma: {} }}",
                c.temperature,
                c.top_p,
                c.top_k,
                c.presence_penalty,
                c.frequency_penalty,
                c.repetition_penalty,
                c.dry_multiplier,
                c.dry_base,
                c.dry_allowed_length,
                c.lz_penalty,
                match c.min_p {
                    Some(value) => format!("Some({value:.4})"),
                    None => "None".to_string(),
                },
                match c.top_n_sigma {
                    Some(value) => format!("Some({value:.4})"),
                    None => "None".to_string(),
                },
            )
        };
        g.push_str(&format!(
            "        TargetPtxSet {{\n\
             \x20           target: KernelTarget {{ arch: \"{arch_clean}\", model: \"{}\", quant: \"{}\" }},\n\
             \x20           modules: {fn_name}(),\n\
             \x20           sampling: SamplingPresets {{\n\
             \x20               thinking_text: {},\n\
             \x20               thinking_coding: {},\n\
             \x20               non_thinking: {},\n\
             \x20               tools: {},\n\
             \x20           }},\n\
             \x20           behavior: ModelBehavior {{\n\
             \x20               thinking_in_tools: {},\n\
             \x20               max_thinking_budget: {},\n\
             \x20               thinking_default: {},\n\
             \x20               honor_eos_inside_thinking: {},\n\
             \x20               fp8_kv_calibration_tokens: {},\n\
             \x20               default_kv_dtype: \"{}\",\n\
             \x20               default_num_drafts: {},\n\
             \x20               disable_tool_steering: {},\n\
             \x20               tool_call_parser: \"{}\",\n\
             \x20               enable_loop_watchdog: {},\n\
             \x20               think_loop_min_repeats: {},\n\
             \x20               think_loop_scan_window: {},\n\
             \x20               confidence_early_stop: {},\n\
             \x20               confidence_run_length: {},\n\
             \x20               fuzzy_repeat_tolerance_div: {},\n\
             \x20               max_inter_tool_prose: {},\n\
             \x20               tscg: {},\n\
             \x20               disable_tool_grammar: {},\n\
             \x20               rollback_resteer: {},\n\
             \x20               rom_head: \"{}\",\n\
             \x20               preserve_thinking: {:?},\n\
             \x20               thinking_answer_reserve: {},\n\
             \x20               thinking_sampling_in_tools: {},\n\
             \x20           }},\n\
             \x20           model_type_matches: vec![{}],\n\
             \x20           dflash: {},\n\
             \x20       }},\n",
            target.model, target.quant,
            fmt_cat(&target.sampling_thinking_text),
            fmt_cat(&target.sampling_thinking_coding),
            fmt_cat(&target.sampling_non_thinking),
            fmt_cat(&target.sampling_tools),
            target.behavior_thinking_in_tools,
            target.behavior_max_thinking_budget,
            target.behavior_thinking_default,
            target.behavior_honor_eos_inside_thinking,
            target.behavior_fp8_kv_calibration_tokens,
            target.behavior_default_kv_dtype,
            target.behavior_default_num_drafts,
            target.behavior_disable_tool_steering,
            target.behavior_tool_call_parser,
            target.behavior_enable_loop_watchdog,
            target.behavior_think_loop_min_repeats,
            target.behavior_think_loop_scan_window,
            target.behavior_confidence_early_stop,
            target.behavior_confidence_run_length,
            target.behavior_fuzzy_repeat_tolerance_div,
            target.behavior_max_inter_tool_prose,
            target.behavior_tscg,
            target.behavior_disable_tool_grammar,
            target.behavior_rollback_resteer,
            target.behavior_rom_head,
            target.behavior_preserve_thinking,
            target.behavior_thinking_answer_reserve,
            target.behavior_thinking_sampling_in_tools,
            target.model_type_matches.iter().map(|m| {
                let hs = match m.hidden_size {
                    Some(v) => format!("Some({v})"),
                    None => "None".to_string(),
                };
                format!("ModelTypeMatch {{ model_type: \"{}\", hidden_size: {hs} }}", m.model_type)
            }).collect::<Vec<_>>().join(", "),
            match &target.dflash {
                None => "None".to_string(),
                Some(d) => format!(
                    "Some(DflashConfig {{ draft_model: \"{}\", gamma: {}, window_size: {}, mask_token_id: {}, target_layer_ids: &[{}] }})",
                    d.draft_model, d.gamma, d.window_size, d.mask_token_id,
                    d.target_layer_ids.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(", "),
                ),
            },
        ));
    }
    g.push_str("    ]\n}\n");

    g
}

#[cfg(not(test))]
pub(super) fn find_cuda_dir() -> PathBuf {
    if let Ok(cuda_home) = env::var("CUDA_HOME") {
        return PathBuf::from(cuda_home);
    }
    for path in &[
        "/usr/local/cuda",
        "/usr/local/cuda-13.0",
        "/usr/local/cuda-13",
    ] {
        let p = PathBuf::from(path);
        if p.join("bin/nvcc").exists() {
            return p;
        }
    }
    panic!("CUDA not found. Set CUDA_HOME or install CUDA toolkit.");
}
