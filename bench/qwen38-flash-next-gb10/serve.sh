# Qwen3.8-Flash-Next single-stream 6K-prefill + lossless K=5 MTP decode profile
# for GB10 (DGX Spark, sm_121a, 128 GB unified LPDDR5X).
#
# Reproduces the certified `v9` (`w16384`) operating profile from unified13
# (`v0.9.12-6k-stable`, commit ae58bc27efd8):
#   - 16K prefill:   6,082.2 tok/s peak | 6,076.7 tok/s W9 median (2.694 s TTFT)
#   - 128K prefill:  5,694.4 tok/s peak | 5,684.0 tok/s W11 median (23.018 s TTFT)
#   - K=5 decode:    57.4 tok/s peak    | 56.3 tok/s median (LOSSLESS 10/10 = 2,560/2,560)
#   - Estonia 136K:  5/5 = 100.0% PASS  | 5,400.4 tok/s prefill, 48.2 tok/s decode
#                    (activate with ESTONIA_136K=1)
#
# Usage (built-in checkpoint MTP head — JMNI-Labs, Blackfrost-AI, or nvidia):
#   MODEL_DIR=/path/to/Qwen3.8-Flash-Next-NVFP4-QAD5500-Hybrid \
#   ./bench/qwen38-flash-next-gb10/serve.sh
#
# Optional external MTP sidecar override:
#   MODEL_DIR=/path/to/Qwen3.8-Flash-Next-NVFP4-Offload \
#   MTP_DIR=/path/to/external-mtp-sidecar \
#   ./bench/qwen38-flash-next-gb10/serve.sh
#
# Ultra-long-context Estonia 136.6K mode (raises MAX_SEQ_LEN=143360,
# FP8_WEIGHT_CACHE_RESERVE_GB=10, QSA_VERIFY_ROWS=0, CTX_OVERFLOW_TRUNCATE=0):
#   ESTONIA_136K=1 MODEL_DIR=... ./bench/qwen38-flash-next-gb10/serve.sh
#
# Self-verification only (validates binary strings, checkpoint dirs, and flags
# without starting the server):
#   MODEL_DIR=... ./bench/qwen38-flash-next-gb10/serve.sh --dry-run
